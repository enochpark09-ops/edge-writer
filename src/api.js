function docSection(work, keys) {
  return keys
    .map((k, i) => {
      const body = work.docs?.[k]
      return `--- 문서 ${i + 1}. ${DOC_LABEL[k]} ---\n${
        body?.trim() || '(비어 있음 — 이 문서를 근거로 한 지적은 하지 않는다)'
      }`
    })
    .join('\n\n')
}

